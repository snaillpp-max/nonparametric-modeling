"""Portable four-stage pulsating-sphere example."""
import os
# New numerical/cache outputs use the explicitly selected output directory.
os.environ.setdefault('OPENBLAS_NUM_THREADS', '1')
os.environ.setdefault('OMP_NUM_THREADS', '1')
os.environ.setdefault('MKL_NUM_THREADS', '1')
import argparse
import json
import hashlib
from pathlib import Path
import sys


def digest(path):
    result = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(chunk)
    return result.hexdigest()


def check_stage(output, stage, binding):
    path = output / f'{stage}_proof.json'
    if not path.is_file():
        raise ValueError(f'Missing {stage} completion proof; run that stage first')
    proof = json.loads(path.read_text(encoding='utf-8'))
    if proof['binding'] != binding:
        raise ValueError(f'{stage} source/configuration does not match this run')
    parent = {'pod': 'generate', 'train': 'pod', 'predict': 'train'}.get(stage)
    if parent and proof['parent_proof_sha256'] != check_stage(output, parent, binding):
        raise ValueError(f'{stage} was produced from different upstream artifacts')
    for name, expected in proof['files'].items():
        if not (output / name).is_file() or digest(output / name) != expected:
            raise ValueError(f'{stage} artifact changed: {name}')
    return digest(path)


def prove_stage(output, stage, binding, parent):
    files = {'generate': ['generation.json', 'fem.npz'],
             'pod': ['pod.npz', 'pod.json', 'training_pairs.npz'],
             'train': ['model.npz', 'selection.json', 'selected.json'],
             'predict': ['prediction.npz', 'prediction_metrics.json']}[stage]
    if stage == 'generate':
        metadata = json.loads((output / 'generation.json').read_text(encoding='utf-8'))
        files += [entry['file'] for group in ('training', 'validation') for entry in metadata[group]]
    proof = dict(binding=binding, parent_proof_sha256=parent,
                 files={name: digest(output / name) for name in files})
    (output / f'{stage}_proof.json').write_text(json.dumps(proof, indent=2), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', choices=['smoke', 'paper'], default='paper')
    parser.add_argument('--output', type=Path, required=True, help='Explicit directory for every generated artifact/cache')
    parser.add_argument('--stage', choices=['all', 'generate', 'pod', 'train', 'predict'], default='all')
    parser.add_argument('--config', type=Path, default=Path(__file__).resolve().with_name('config.json'))
    args = parser.parse_args()
    output = args.output.expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    cache = output / '_cache'
    for name in ['tmp', 'matplotlib', 'numba', 'pycache']:
        (cache / name).mkdir(parents=True, exist_ok=True)
    os.environ['TMP'] = os.environ['TEMP'] = os.environ['TMPDIR'] = str(cache / 'tmp')
    os.environ['MPLCONFIGDIR'] = str(cache / 'matplotlib')
    os.environ['NUMBA_CACHE_DIR'] = str(cache / 'numba')
    sys.pycache_prefix = str(cache / 'pycache')
    config = json.loads(args.config.read_text(encoding='utf-8'))
    identity = dict(physics=config['physics'], settings=config['profiles'][args.profile],
                    feature_seed=config['feature_seed'], integrator=config['integrator'], prediction=config['prediction'])
    generation_file = output / 'generation.json'
    if generation_file.exists():
        saved = json.loads(generation_file.read_text(encoding='utf-8'))
        if saved['profile'] != args.profile or saved.get('pipeline_config') != identity:
            parser.error('Existing output has a different profile/config; use matching settings or a new output directory')
    elif args.stage not in ['all', 'generate']:
        parser.error('Run the generate stage first in this output directory')
    source = Path(__file__).resolve().parent
    source_hashes = {name: hashlib.sha256((source / name).read_bytes()).hexdigest()
                     for name in ['run.py', 'physics.py', 'generate.py', 'pod.py', 'train.py', 'predict.py']}
    if generation_file.exists() and saved.get('source_sha256') != source_hashes:
        parser.error('Existing output was generated by different source files; use a new output directory')
    config['_source_hashes'] = source_hashes
    config['_pipeline_identity'] = identity
    config['_config_sha256'] = hashlib.sha256(args.config.read_bytes()).hexdigest()
    import numpy as np
    import scipy
    from physics import constants
    import generate
    import pod
    import train
    import predict
    p = constants(config['physics'])
    stages = ['generate', 'pod', 'train', 'predict'] if args.stage == 'all' else [args.stage]
    binding = dict(profile=args.profile, pipeline=identity, source_sha256=source_hashes)
    for stage in stages:
        parent_name = {'pod': 'generate', 'train': 'pod', 'predict': 'train'}.get(stage)
        parent = check_stage(output, parent_name, binding) if parent_name else None
        print(f'Running {stage} ({args.profile}) in {output}', flush=True)
        {'generate': generate, 'pod': pod, 'train': train, 'predict': predict}[stage].run(output, config, args.profile, p)
        prove_stage(output, stage, binding, parent)
    (output / 'runtime.json').write_text(json.dumps(dict(python=sys.version, numpy=np.__version__, scipy=scipy.__version__,
                                                       profile=args.profile, stages=stages, output=str(output),
                                                       source_sha256=source_hashes, config_sha256=config['_config_sha256']), indent=2), encoding='utf-8')


if __name__ == '__main__':
    main()
